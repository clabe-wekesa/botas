#!/usr/bin/env python3

import argparse
from pathlib import Path

import matplotlib.pyplot as plt
import pandas as pd


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Plot precision, recall, and F1 score from the "
            "BOTAS-versus-RegulonDB operon benchmark."
        )
    )

    root = Path(__file__).resolve().parent.parent

    default_summary = (
        root
        / "results"
        / "operons"
        / "benchmark"
        / "botas_vs_regulondb_summary.tsv"
    )

    default_outdir = (
        root
        / "results"
        / "operons"
        / "figures"
    )

    parser.add_argument(
        "--summary",
        default=str(default_summary),
        help=(
            "Operon benchmark summary TSV generated by "
            "benchmark_operon_links_unordered.py"
        ),
    )

    parser.add_argument(
        "--outdir",
        default=str(default_outdir),
        help="Directory for PNG and PDF figure output",
    )

    args = parser.parse_args()

    summary_file = Path(args.summary)
    outdir = Path(args.outdir)

    if not summary_file.is_file():
        raise FileNotFoundError(
            f"Benchmark summary not found: {summary_file}"
        )

    outdir.mkdir(parents=True, exist_ok=True)

    out_png = (
        outdir
        / "botas_operon_regulondb_benchmark.png"
    )

    out_pdf = (
        outdir
        / "botas_operon_regulondb_benchmark.pdf"
    )

    df = pd.read_csv(
        summary_file,
        sep="\t",
    )

    required = {"metric", "value"}
    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            "Summary file is missing required columns: "
            + ", ".join(sorted(missing))
        )

    metrics = dict(
        zip(
            df["metric"],
            df["value"],
        )
    )

    required_metrics = {
        "precision",
        "recall",
        "f1",
        "reference_links_mapped",
        "predicted_links",
        "true_positives",
        "false_positives",
        "false_negatives",
    }

    missing_metrics = (
        required_metrics - set(metrics)
    )

    if missing_metrics:
        raise ValueError(
            "Summary file is missing required metrics: "
            + ", ".join(sorted(missing_metrics))
        )

    plot_df = pd.DataFrame(
        {
            "Metric": [
                "Precision",
                "Recall",
                "F1-score",
            ],
            "Value": [
                float(metrics["precision"]),
                float(metrics["recall"]),
                float(metrics["f1"]),
            ],
        }
    )

    plt.figure(figsize=(5.5, 4.5))

    bars = plt.bar(
        plot_df["Metric"],
        plot_df["Value"],
    )

    plt.ylim(0, 1.05)
    plt.ylabel("Score")
    plt.title(
        "BOTAS operon inference benchmark"
    )

    for bar, value in zip(
        bars,
        plot_df["Value"],
    ):
        plt.text(
            bar.get_x()
            + bar.get_width() / 2,
            value + 0.025,
            f"{value:.3f}",
            ha="center",
            va="bottom",
        )

    note = (
        f"RegulonDB links = "
        f"{int(float(metrics['reference_links_mapped']))}\n"
        f"Predicted links = "
        f"{int(float(metrics['predicted_links']))}\n"
        f"TP = "
        f"{int(float(metrics['true_positives']))}, "
        f"FP = "
        f"{int(float(metrics['false_positives']))}, "
        f"FN = "
        f"{int(float(metrics['false_negatives']))}"
    )

    plt.text(
        0.5,
        0.08,
        note,
        transform=plt.gca().transAxes,
        ha="center",
        va="bottom",
        fontsize=9,
        bbox=dict(
            facecolor="white",
            edgecolor="black",
            linewidth=0.5,
            alpha=0.85,
        ),
    )

    plt.tight_layout()

    plt.savefig(
        out_png,
        dpi=300,
    )

    plt.savefig(
        out_pdf,
    )

    plt.close()

    print(f"Summary: {summary_file}")
    print(f"Saved PNG: {out_png}")
    print(f"Saved PDF: {out_pdf}")


if __name__ == "__main__":
    main()