#!/usr/bin/env python3

import argparse
from pathlib import Path

import pandas as pd


def norm_link(a, b):
    """
    Normalize a gene pair so that A-B and B-A are treated as equivalent.
    This avoids penalizing reverse-strand operons represented in opposite order.
    """
    return tuple(sorted((a, b)))


def load_gene_map(path):
    df = pd.read_csv(path, sep="\t")

    required = {"gene_name", "gene_id"}
    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            "Gene map is missing required columns: "
            + ", ".join(sorted(missing))
        )

    return dict(zip(df["gene_name"], df["gene_id"]))


def load_reference_links(path, gene_map):
    df = pd.read_csv(path, sep="\t")

    required = {"geneA", "geneB"}
    missing = required - set(df.columns)

    if missing:
        raise ValueError(
            "RegulonDB links file is missing required columns: "
            + ", ".join(sorted(missing))
        )

    mapped = []
    unmapped = []

    for _, row in df.iterrows():
        gene_a = str(row["geneA"])
        gene_b = str(row["geneB"])

        if gene_a in gene_map and gene_b in gene_map:
            mapped.append(
                norm_link(
                    gene_map[gene_a],
                    gene_map[gene_b],
                )
            )
        else:
            unmapped.append((gene_a, gene_b))

    return set(mapped), unmapped


def load_botas_links(path):
    df = pd.read_csv(path, sep="\t")

    if "gene_ids" not in df.columns:
        raise ValueError(
            "BOTAS operon file must contain a gene_ids column"
        )

    links = set()

    for _, row in df.iterrows():
        genes = [
            gene.strip()
            for gene in str(row["gene_ids"]).split(",")
            if gene.strip() and gene.strip() != "nan"
        ]

        if len(genes) < 2:
            continue

        for gene_a, gene_b in zip(genes, genes[1:]):
            links.add(
                norm_link(gene_a, gene_b)
            )

    return links


def write_links(path, links):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "w") as out:
        out.write("geneA\tgeneB\n")

        for gene_a, gene_b in sorted(links):
            out.write(f"{gene_a}\t{gene_b}\n")


def main():
    parser = argparse.ArgumentParser(
        description=(
            "Benchmark BOTAS-predicted adjacent operon gene links "
            "against RegulonDB reference links. Gene-pair order is "
            "ignored so that A-B and B-A are treated as equivalent."
        )
    )

    root = Path(__file__).resolve().parent.parent
    default_outdir = root / "results" / "operons" / "benchmark"

    parser.add_argument(
        "--gene-map",
        required=True,
        help=(
            "TSV mapping RegulonDB gene names to annotation gene IDs. "
            "Required columns: gene_name, gene_id"
        ),
    )

    parser.add_argument(
        "--regulondb-links",
        required=True,
        help=(
            "RegulonDB adjacent-gene links generated by "
            "extract_regulondb_operon_links.py"
        ),
    )

    parser.add_argument(
        "--botas-operons",
        required=True,
        help="BOTAS operon TSV containing a gene_ids column",
    )

    parser.add_argument(
        "--out-prefix",
        default=str(default_outdir / "botas_vs_regulondb"),
        help=(
            "Prefix for output files "
            "(default: results/operons/benchmark/botas_vs_regulondb)"
        ),
    )

    args = parser.parse_args()

    gene_map_path = Path(args.gene_map)
    regulondb_path = Path(args.regulondb_links)
    botas_path = Path(args.botas_operons)
    out_prefix = Path(args.out_prefix)

    for path, label in [
        (gene_map_path, "Gene map"),
        (regulondb_path, "RegulonDB links"),
        (botas_path, "BOTAS operon file"),
    ]:
        if not path.is_file():
            raise FileNotFoundError(
                f"{label} not found: {path}"
            )

    out_prefix.parent.mkdir(parents=True, exist_ok=True)

    gene_map = load_gene_map(gene_map_path)

    ref_links, unmapped = load_reference_links(
        regulondb_path,
        gene_map,
    )

    pred_links = load_botas_links(
        botas_path
    )

    true_positives = ref_links & pred_links
    false_positives = pred_links - ref_links
    false_negatives = ref_links - pred_links

    precision = (
        len(true_positives)
        / (len(true_positives) + len(false_positives))
        if (len(true_positives) + len(false_positives))
        else 0.0
    )

    recall = (
        len(true_positives)
        / (len(true_positives) + len(false_negatives))
        if (len(true_positives) + len(false_negatives))
        else 0.0
    )

    f1 = (
        2 * precision * recall / (precision + recall)
        if (precision + recall)
        else 0.0
    )

    summary_file = Path(
        str(out_prefix) + "_summary.tsv"
    )

    with open(summary_file, "w") as out:
        out.write("metric\tvalue\n")
        out.write(f"reference_links_mapped\t{len(ref_links)}\n")
        out.write(f"predicted_links\t{len(pred_links)}\n")
        out.write(f"true_positives\t{len(true_positives)}\n")
        out.write(f"false_positives\t{len(false_positives)}\n")
        out.write(f"false_negatives\t{len(false_negatives)}\n")
        out.write(f"unmapped_reference_links\t{len(unmapped)}\n")
        out.write(f"precision\t{precision:.6f}\n")
        out.write(f"recall\t{recall:.6f}\n")
        out.write(f"f1\t{f1:.6f}\n")

    write_links(
        str(out_prefix) + "_TP.tsv",
        true_positives,
    )

    write_links(
        str(out_prefix) + "_FP.tsv",
        false_positives,
    )

    write_links(
        str(out_prefix) + "_FN.tsv",
        false_negatives,
    )

    pd.DataFrame(
        unmapped,
        columns=["geneA", "geneB"],
    ).to_csv(
        str(out_prefix) + "_unmapped_reference.tsv",
        sep="\t",
        index=False,
    )

    print(open(summary_file).read())
    print(f"Summary written to: {summary_file}")


if __name__ == "__main__":
    main()